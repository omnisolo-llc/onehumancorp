use crate::domain::subscription::SubscriptionPlan;
use sqlx::PgPool as DbPool;
use std::sync::Arc;
use uuid::Uuid;
use chrono::Utc;

pub struct SubscriptionService {
    db: Arc<DbPool>,
}

#[tonic::async_trait]
impl ::server_ohc::app::subscription_engine_service_server::SubscriptionEngineService for SubscriptionService {
    async fn toggle_product_recurring(
        &self,
        request: tonic::Request<::server_ohc::app::ToggleProductRecurringRequest>,
    ) -> Result<tonic::Response<::server_ohc::app::ToggleProductRecurringResponse>, tonic::Status> {
        let req = request.into_inner();
        let plan_id = Uuid::new_v4().to_string();

        let q = "
            INSERT INTO subscription_plans (id, tenant_id, product_id, interval, interval_count, status, discount_percentage)
            VALUES ($1, $2, $3, $4, 1, 'active', 0)
            ON CONFLICT (id) DO UPDATE SET interval = $4;
        ";

        sqlx::query(q)
            .bind(&plan_id)
            .bind(&req.tenant_id)
            .bind(&req.product_id)
            .bind(&req.interval)
            .execute(&*self.db)
            .await
            .map_err(|e| tonic::Status::internal(e.to_string()))?;

        Ok(tonic::Response::new(::server_ohc::app::ToggleProductRecurringResponse {
            success: true,
            plan_id,
        }))
    }

    async fn create_subscription_checkout(
        &self,
        request: tonic::Request<::server_ohc::app::CreateSubscriptionCheckoutRequest>,
    ) -> Result<tonic::Response<::server_ohc::app::CreateSubscriptionCheckoutResponse>, tonic::Status> {
        let req = request.into_inner();

        // Mock checkout session generated by a vaulted payment gateway wrapper.
        let checkout_url = format!("https://checkout.ohc.test/pay/sub_{}", Uuid::new_v4());
        let intent_id = Uuid::new_v4().to_string();

        Ok(tonic::Response::new(::server_ohc::app::CreateSubscriptionCheckoutResponse {
            checkout_url,
            intent_id,
        }))
    }

    async fn generate_magic_link(
        &self,
        request: tonic::Request<::server_ohc::app::GenerateMagicLinkRequest>,
    ) -> Result<tonic::Response<::server_ohc::app::GenerateMagicLinkResponse>, tonic::Status> {
        let req = request.into_inner();
        let token = Uuid::new_v4().to_string(); // In a real app this would be a signed JWT
        let magic_link_url = format!("https://ohc.test/portal/subscription?token={}&sub={}", token, req.subscription_id);

        Ok(tonic::Response::new(::server_ohc::app::GenerateMagicLinkResponse {
            magic_link_url,
        }))
    }

    async fn manage_customer_subscription(
        &self,
        request: tonic::Request<::server_ohc::app::ManageCustomerSubscriptionRequest>,
    ) -> Result<tonic::Response<::server_ohc::app::ManageCustomerSubscriptionResponse>, tonic::Status> {
        let req = request.into_inner();

        let new_status = match req.action.as_str() {
            "pause" => "paused",
            "cancel" => "canceled",
            "resume" => "active",
            _ => return Err(tonic::Status::invalid_argument("Invalid action")),
        };

        sqlx::query("UPDATE subscriptions SET status = $1 WHERE id = $2 AND tenant_id = $3")
            .bind(new_status)
            .bind(&req.subscription_id)
            .bind(&req.tenant_id)
            .execute(&*self.db)
            .await
            .map_err(|e| tonic::Status::internal(e.to_string()))?;

        Ok(tonic::Response::new(::server_ohc::app::ManageCustomerSubscriptionResponse {
            success: true,
            new_status: new_status.to_string(),
        }))
    }

    async fn subscription_dunning_callback(
        &self,
        request: tonic::Request<::server_ohc::app::SubscriptionDunningCallbackRequest>,
    ) -> Result<tonic::Response<::server_ohc::app::SubscriptionDunningCallbackResponse>, tonic::Status> {
        let req = request.into_inner();

        // Log AI interceptor action
        tracing::info!("Finance AI Intercepted Dunning for subscription: {}", req.subscription_id);

        Ok(tonic::Response::new(::server_ohc::app::SubscriptionDunningCallbackResponse {
            handled_by_ai: true,
            action_taken: "Sent follow-up SMS with magic link to update card".to_string(),
        }))
    }
}

impl SubscriptionService {
    pub fn new(db: Arc<DbPool>) -> Self {
        Self { db }
    }

    pub async fn create_plan(&self, tenant_id: &str, name: &str, description: &str, amount: i64, currency: &str, interval: &str) -> Result<SubscriptionPlan, String> {
        let plan = SubscriptionPlan {
            id: Uuid::new_v4().to_string(),
            tenant_id: tenant_id.to_string(),
            name: name.to_string(),
            description: description.to_string(),
            amount,
            currency: currency.to_string(),
            interval: interval.to_string(),
            active: true,
            created_at: Utc::now().timestamp(),
        };

        let db = self.db.clone();

        let q = "
            CREATE TABLE IF NOT EXISTS subscription_plans (
                id TEXT PRIMARY KEY,
                tenant_id TEXT NOT NULL,
                name TEXT NOT NULL,
                description TEXT NOT NULL,
                amount BIGINT NOT NULL,
                currency TEXT NOT NULL,
                interval TEXT NOT NULL,
                active BOOLEAN NOT NULL,
                created_at BIGINT NOT NULL
            );
        ";

        sqlx::query(q).execute(&*db).await.map_err(|e| e.to_string())?;

        sqlx::query("
            INSERT INTO subscription_plans (id, tenant_id, name, description, amount, currency, interval, active, created_at)
            VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
        ")
        .bind(&plan.id)
        .bind(&plan.tenant_id)
        .bind(&plan.name)
        .bind(&plan.description)
        .bind(plan.amount)
        .bind(&plan.currency)
        .bind(&plan.interval)
        .bind(plan.active)
        .bind(plan.created_at)
        .execute(&*db)
        .await
        .map_err(|e| e.to_string())?;

        Ok(plan)
    }
}
