use serde::{Serialize, Deserialize};
use uuid::Uuid;
use chrono::{DateTime, Utc};
use std::sync::Arc;
use crate::orchestration::departments::types::{DepartmentType, ApprovalRequest, ActionRisk};
use crate::orchestration::departments::orchestrator::DepartmentOrchestrator;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AIAgentPersona {
    pub id: String,
    pub name: String,
    pub system_prompt: String,
    pub capabilities: Vec<String>,
    pub tenant_id: String,
}

impl AIAgentPersona {
    pub fn new(name: &str, system_prompt: &str, capabilities: Vec<String>, tenant_id: &str) -> Self {
        Self {
            id: Uuid::new_v4().to_string(),
            name: name.to_string(),
            system_prompt: system_prompt.to_string(),
            capabilities,
            tenant_id: tenant_id.to_string(),
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub enum WorkflowState {
    Pending,
    InProgress,
    AwaitingApproval,
    Approved,
    Rejected,
    Completed,
    Failed,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AIaaSWorkflow {
    pub id: String,
    pub workflow_type: String,
    pub persona_id: String,
    pub tenant_id: String,
    pub state: WorkflowState,
    pub created_at: DateTime<Utc>,
    pub payload: serde_json::Value,
}

impl AIaaSWorkflow {
    pub fn new(workflow_type: &str, persona_id: &str, tenant_id: &str, payload: serde_json::Value) -> Self {
        Self {
            id: Uuid::new_v4().to_string(),
            workflow_type: workflow_type.to_string(),
            persona_id: persona_id.to_string(),
            tenant_id: tenant_id.to_string(),
            state: WorkflowState::Pending,
            created_at: Utc::now(),
            payload,
        }
    }
}

pub struct AIaaSExecutionEngine {
    orchestrator: Arc<DepartmentOrchestrator>,
}

impl AIaaSExecutionEngine {
    pub fn new(orchestrator: Arc<DepartmentOrchestrator>) -> Self {
        Self { orchestrator }
    }

    pub async fn trigger_workflow(
        &self,
        persona: &AIAgentPersona,
        mut workflow: AIaaSWorkflow,
    ) -> Result<AIaaSWorkflow, String> {
        workflow.state = WorkflowState::InProgress;

        let draft_copy = format!(
            "AI Draft generated by {}: {} - {}",
            persona.name, workflow.workflow_type,
            workflow.payload.get("context").and_then(|c| c.as_str()).unwrap_or("General context")
        );

        let approval_payload = serde_json::json!({
            "feature_type": "aiaas_workflow",
            "workflow_id": workflow.id,
            "persona_name": persona.name,
            "draft_copy": draft_copy,
            "original_payload": workflow.payload
        });

        self.orchestrator.execute_action(
            DepartmentType::BusinessAdvisory, // Use BusinessAdvisory as the default for generic AIaaS
            format!("AI Workflow: {}", workflow.workflow_type),
            workflow.tenant_id.clone(),
            ActionRisk::DraftForReview,
            approval_payload,
        ).await?;

        workflow.state = WorkflowState::AwaitingApproval;

        Ok(workflow)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn test_aiaas_workflow_creation_and_execution() {
        let tenant_id = "test-tenant-123";

        let persona = AIAgentPersona::new(
            "Test Persona",
            "You are a helpful AI assistant.",
            vec!["draft_content".to_string()],
            tenant_id
        );

        assert_eq!(persona.name, "Test Persona");
        assert_eq!(persona.tenant_id, tenant_id);

        let workflow = AIaaSWorkflow::new(
            "test_workflow",
            &persona.id,
            tenant_id,
            serde_json::json!({"context": "Writing a test email."})
        );

        assert_eq!(workflow.workflow_type, "test_workflow");
        assert_eq!(workflow.state, WorkflowState::Pending);
    }
}
