#[tokio::test]
async fn test_mobile_shaper_snapshot_integrity() {
    let mut snapshot = ::server_ohc::app::DashboardSnapshot {
        agents: vec![::server_ohc::agent::Agent { id: "a1".to_string(), name: "Agent Name".to_string(), ..Default::default() }],
        meetings: vec![::server_ohc::app::MeetingRoom { id: "m1".to_string(), transcript: vec![::server_ohc::agent::AgentMessage { content: "test".to_string(), ..Default::default() }], ..Default::default() }],
        ..Default::default()
    };

    ::server_utils::mobile_shaper::shape_if_needed(&mut snapshot, true);

    assert_eq!(snapshot.agents[0].name, "");
    assert!(snapshot.meetings[0].transcript.is_empty());
}

#[tokio::test]
async fn test_prompt_compression_efficiency() {
    let original = "This is a very long prompt with a lot of stop words and conversational filler that we should remove to save tokens.";
    let compressed = ::server_pricing::compression::reduce_tokens(original);
    assert!(compressed.len() < original.len());
    assert!(!compressed.contains(" with "));
}

#[tokio::test]
async fn test_hub_async_concurrency() {
    let (tx, _) = mpsc::channel(100);
    let pg_pool = sqlx::postgres::PgPoolOptions::new().connect_lazy("postgres://localhost/dummy").unwrap();
    let hub = Arc::new(Hub::new(tx, pg_pool));

    let hub1 = hub.clone();
    let hub2 = hub.clone();

    let h1 = tokio::spawn(async move {
        hub1.register_agent(::server_ohc::orchestration::Agent { id: "agent1".to_string(), ..Default::default() }).await;
    });

    let h2 = tokio::spawn(async move {
        hub2.get_agents().await;
    });

    let _ = tokio::join!(h1, h2);
}
