use ::server_common::Claims;
use ::sqlx::PgPool;
use serde_json::{json, Value};
use uuid::Uuid;

pub struct StorefrontAgent {
    pub pool: PgPool,
}

impl StorefrontAgent {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn generate_storefront(
        &self,
        tenant_id: Uuid,
        description: &str,
    ) -> Result<Value, String> {
        let blocks = vec![
            json!({
                "block_type": "HeroBlock",
                "content": {
                    "headline": format!("{} Store", description),
                    "copy": "Generated by StorefrontAgent",
                },
                "sort_order": 0
            }),
            json!({
                "block_type": "ProductGridBlock",
                "content": {
                    "items": []
                },
                "sort_order": 1
            })
        ];

        let draft = json!({
            "theme": "light",
            "pages": [{
                "path": "/",
                "title": "Home",
                "blocks": blocks,
                "seo_metadata": {}
            }]
        });

        Ok(draft)
    }
}
