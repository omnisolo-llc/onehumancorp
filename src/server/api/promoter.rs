use axum::{
    extract::{Json, State, Query, Extension},
    response::IntoResponse,
    routing::{post, get},
    Router,
};
use serde::{Deserialize, Serialize};
use std::sync::Arc;
use crate::db::DB;

#[derive(Deserialize)]
pub struct DraftRequest {
    pub prompt: String,
    pub model: Option<String>,
}

#[derive(Serialize)]
struct ChatRequest {
    model: String,
    messages: Vec<ChatMessage>,
}

#[derive(Serialize)]
pub struct DraftResponse {
    pub text: String,
}

#[derive(Serialize, Deserialize)]
struct ChatMessage {
    role: String,
    content: String,
}

#[derive(Deserialize)]
pub struct SendRequest {
    pub body: String,
    pub to: Option<Vec<String>>,
}

#[derive(Serialize)]
pub struct SendResponse {
    pub status: String,
}

pub fn router<S: Clone + Send + Sync + 'static>(db: Arc<DB>) -> Router<S> {
    Router::new()
        .route("/draft", post(draft_handler))
        .route("/send", post(send_handler))
        .route("/webhook/open", get(open_tracking_webhook))
        .with_state(db)
}

async fn draft_handler(
    State(_db): State<Arc<DB>>,
    Json(req): Json<DraftRequest>,
) -> impl IntoResponse {
    let api_key = std::env::var("OPENAI_API_KEY").unwrap_or_default();

    // In standalone / default environment lacking mesh transport authentication context,
    // this acts as an unauthenticated dev stub. In production cloud deployments,
    // access to `/api/agents/*` is explicitly firewalled at the ingress/gateway level
    // unless accessed internally by trusted microservices.

    if api_key.is_empty() {
        let text = if req.prompt.contains("New arrivals") {
            "Subject: Check Out Our New Arrivals!\n\nHi there,\n\nWe're excited to announce that new stock has arrived! Visit our store today to see the latest additions.\n\nBest,\nThe Team"
        } else if req.prompt.contains("Flash sale") {
            "Subject: ⚡ Flash Sale - Don't Miss Out!\n\nHi there,\n\nOur biggest flash sale of the season is on! Use code FLASH20 at checkout for 20% off all items.\n\nHurry, sale ends soon!\n\nBest,\nThe Team"
        } else if req.prompt.contains("Thank you") {
            "Subject: Thank You for Your Support!\n\nHi there,\n\nWe just wanted to take a moment to thank you for being a valued customer. We appreciate your business and hope to see you again soon.\n\nBest,\nThe Team"
        } else {
            "Subject: Update from Our Store\n\nHi there,\n\nHere is an update from our store: This is a custom email draft generated by our AI agent.\n\nBest,\nThe Team"
        };
        return axum::response::Json(DraftResponse { text: text.to_string() }).into_response();
    }

    let client = reqwest::Client::new();
    let chat_req = ChatRequest {
        model: req.model.unwrap_or_else(|| "gpt-4o".to_string()),
        messages: vec![
            ChatMessage {
                role: "system".to_string(),
                content: "You are an expert marketing copywriter for small businesses. You write short, punchy, engaging emails. Output ONLY the Subject line and Body of the email. Do not include introductory text or markdown wrappers.".to_string()
            },
            ChatMessage {
                role: "user".to_string(),
                content: req.prompt
            }
        ]
    };

    let res = client.post("https://api.openai.com/v1/chat/completions")
        .header("Authorization", format!("Bearer {}", api_key))
        .json(&chat_req)
        .send()
        .await;

    match res {
        Ok(response) => {
            if let Ok(json) = response.json::<serde_json::Value>().await {
                if let Some(content) = json["choices"][0]["message"]["content"].as_str() {
                    return axum::response::Json(DraftResponse { text: content.to_string() }).into_response();
                }
            }
        },
        Err(e) => {
            println!("Error calling OpenAI API: {}", e);
        }
    }

    let fallback_text = "Subject: Draft Email\n\nHello, this is a fallback email draft due to an API error.";
    axum::response::Json(DraftResponse { text: fallback_text.to_string() }).into_response()
}

#[derive(Serialize)]
struct ResendRequest {
    from: String,
    to: Vec<String>,
    subject: String,
    html: String,
}

async fn send_handler(
    State(db): State<Arc<DB>>,
    Json(req): Json<SendRequest>,
) -> impl IntoResponse {
    let api_key = std::env::var("RESEND_API_KEY").unwrap_or_default();
    if api_key.is_empty() {
        return axum::response::Json(SendResponse { status: "simulated_success".to_string() }).into_response();
    }

    let subject = req.body.lines().next().unwrap_or("Store Update").replace("Subject: ", "");
    let html = req.body.replace("\n", "<br>");

    let campaign_id = uuid::Uuid::new_v4().to_string();
    let tenant_id = std::env::var("OHC_BOOTSTRAP_ORG_ID").unwrap_or_else(|_| "system".to_string());

    let to_list = req.to.unwrap_or_else(|| vec!["delivered@resend.dev".to_string()]);
    let to_list = if to_list.is_empty() { vec!["delivered@resend.dev".to_string()] } else { to_list };

    // Record the sent emails in the database
    let mut pg_conn = None;
    match &db.store {
        crate::db::DbStore::Postgres => {
            match db.pool.acquire().await {
                Ok(c) => pg_conn = Some(c),
                Err(_) => {
                    return axum::response::Json(SendResponse { status: "db_error".to_string() }).into_response();
                }
            }
        },
        _ => {}
    };

    if let Some(mut conn) = pg_conn {
        for recipient in &to_list {
            let id = uuid::Uuid::new_v4().to_string();
            let _ = sqlx::query(
                "INSERT INTO email_campaign_metrics (id, tenant_id, campaign_id, recipient, sent_at) VALUES ($1, $2, $3, $4, CURRENT_TIMESTAMP)"
            )
            .bind(&id)
            .bind(&tenant_id)
            .bind(&campaign_id)
            .bind(&recipient)
            .execute(&mut *conn)
            .await;
        }
    }

    // Embed tracking pixel
    let tracking_pixel = format!("<img src=\"https://mybusiness.ohc.app/api/agents/promoter/webhook/open?campaign_id={}\" width=\"1\" height=\"1\" />", campaign_id);
    let mut html_with_tracking = html.clone();
    html_with_tracking.push_str(&tracking_pixel);

    let resend_req = ResendRequest {
        from: "onboarding@resend.dev".to_string(), // Resend free tier allows sending from this address
        to: to_list,
        subject,
        html: html_with_tracking,
    };

    let client = reqwest::Client::new();
    let res = client.post("https://api.resend.com/emails")
        .header("Authorization", format!("Bearer {}", api_key))
        .json(&resend_req)
        .send()
        .await;

    match res {
        Ok(response) => {
            if response.status().is_success() {
                axum::response::Json(SendResponse { status: "success".to_string() }).into_response()
            } else {
                let err_text = response.text().await.unwrap_or_default();
                println!("Error sending email: {}", err_text);
                axum::response::Json(SendResponse { status: "error".to_string() }).into_response()
            }
        }
        Err(e) => {
            println!("Network error sending email: {}", e);
            axum::response::Json(SendResponse { status: "error".to_string() }).into_response()
        }
    }
}

#[derive(Deserialize)]
pub struct WebhookQuery {
    campaign_id: String,
}

pub async fn open_tracking_webhook(
    State(db): State<Arc<DB>>,
    Query(query): Query<WebhookQuery>,
) -> impl IntoResponse {
    let mut pg_conn = None;
    match &db.store {
        crate::db::DbStore::Postgres => {
            match db.pool.acquire().await {
                Ok(mut c) => {
                    use sqlx::Executor;
                    let _ = c.execute("SET app.current_tenant = 'system'").await;
                    pg_conn = Some(c);
                },
                Err(_) => return (axum::http::StatusCode::INTERNAL_SERVER_ERROR, "DB Connection Error").into_response(),
            }
        },
        _ => {}
    };

    if let Some(mut conn) = pg_conn {
        let _ = sqlx::query(
            "UPDATE email_campaign_metrics SET opened = TRUE, opened_at = CURRENT_TIMESTAMP WHERE campaign_id = $1 "
        )
        .bind(&query.campaign_id)
        .execute(&mut *conn)
        .await;
    }

    // Return a 1x1 transparent GIF
    let transparent_pixel: [u8; 43] = [
        0x47, 0x49, 0x46, 0x38, 0x39, 0x61, 0x01, 0x00, 0x01, 0x00, 0x80, 0x00, 0x00, 0xff, 0xff, 0xff,
        0x00, 0x00, 0x00, 0x2c, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x02, 0x02, 0x44,
        0x01, 0x00, 0x3b, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ];

    (
        [(axum::http::header::CONTENT_TYPE, "image/gif")],
        axum::body::Bytes::from(transparent_pixel.to_vec()),
    )
    .into_response()
}
