import { test, expect } from '@playwright/test';

test.describe('Chaos Resilience Parity Testing', () => {

    test('agent transitions to PAUSED on timeout simulation', async ({ page }) => {
        // Go to dashboard
        await page.goto('/dashboard');

        // Mock the backend API throwing a timeout error
        await page.route('**/api/v1/agents/*/tasks', async route => {
            const request = route.request();
            if (request.method() === 'POST') {
                await route.fulfill({
                    status: 504,
                    contentType: 'application/json',
                    body: JSON.stringify({ error: "LLM API unavailable or exhausted: rate limit exceeded" }),
                });
            } else {
                await route.continue();
            }
        });

        // Trigger agent action
        await page.click('button:has-text("Assign Task")');

        // Check if agent goes to PAUSED state
        const statusBadge = page.locator('.agent-status-badge');
        await expect(statusBadge).toHaveText('PAUSED', { timeout: 10000 });

        // Check for the error notification dialog explicitly generated by the circuit breaker transition
        const notification = page.locator('.notification-toast');
        await expect(notification).toContainText('LLM API connection unstable. Agent paused safely.');
    });

    test('hybrid sync lag degrades gracefully showing cache', async ({ page }) => {
        await page.goto('/dashboard/metrics');

        // Mock 2500ms delay on DB read, triggering Standalone fallback read
        await page.route('**/api/v1/metrics/sync', async route => {
            await new Promise(resolve => setTimeout(resolve, 2500));
            await route.fulfill({
                status: 200,
                contentType: 'application/json',
                body: JSON.stringify({ cached: true, value: "offline-data" })
            });
        });

        await page.click('button:has-text("Refresh Metrics")');

        // It shouldn't crash, it should show cached warning
        const warning = page.locator('.cache-warning-banner');
        await expect(warning).toBeVisible({ timeout: 4000 });
        await expect(warning).toContainText('Operating in degraded mode');
    });

    test('cloud mode token budget exhaustion fallback', async ({ page }) => {
        await page.goto('/settings/billing');

        // Mock token exhaustion response
        await page.route('**/api/v1/settings/execute_action', async route => {
            await route.fulfill({
                status: 429,
                contentType: 'application/json',
                body: JSON.stringify({ error: "AI Budget exhausted. Agents degraded to reactive mode. Please upgrade your plan." })
            });
        });

        await page.click('button:has-text("Auto-Execute Routine")');

        // Expect upgrade prompt instead of crash
        const modal = page.locator('.upgrade-modal');
        await expect(modal).toBeVisible();
        await expect(modal).toContainText('Agents degraded to reactive mode');
    });
});
