import { test, expect } from './fixtures';

test.describe('Tool Integrations Q2 Research Additions (Functional CUJ)', () => {
  test.beforeEach(async ({ page }) => {
    await page.goto('/');
  });

  test('Ayrshare: Connect Meta OAuth and view Unified Customer Inbox', async ({ page }) => {
    await page.getByRole('button', { name: 'Marketing' }).click();
    await expect(page.getByRole('heading', { name: 'Marketing & Advertising' })).toBeVisible();

    await expect(page.getByRole('heading', { name: 'Ayrshare Social Media' })).toBeVisible();
    await page.getByRole('button', { name: 'Connect Socials via Meta OAuth' }).click();
    await expect(page.getByRole('button', { name: 'Connected to Meta ✓' })).toBeVisible();

    await expect(page.getByRole('heading', { name: 'Unified Customer Inbox' })).toBeVisible();
    await expect(page.getByText('IG: @maya_bakes')).toBeVisible();
    await page.getByRole('button', { name: 'Draft Reply' }).click();
    await expect(page.getByRole('button', { name: 'Draft generated by The Ambassador...' })).toBeVisible();
  });

  test('Listmonk: Trigger embedded plain-text email campaigns', async ({ page }) => {
    await page.getByRole('button', { name: 'Marketing' }).click();

    await expect(page.getByRole('heading', { name: 'Listmonk Email Campaigns' })).toBeVisible();
    await page.getByPlaceholder('Draft an email about our new summer dresses.').fill('Hello past customers, checkout our new stock!');
    await page.getByRole('button', { name: "Send Email to 'bought-shoes' Segment" }).click();

    await expect(page.getByText('✓ Email dispatched via Listmonk to 432 customers.')).toBeVisible();
  });

  test('Cal.com: Sync personal calendars in Operations', async ({ page }) => {
    await page.getByRole('button', { name: 'Operations' }).click();
    await expect(page.getByRole('heading', { name: 'Operations' })).toBeVisible();

    await expect(page.getByRole('heading', { name: 'Cal.com Sync' })).toBeVisible();
    await page.getByRole('button', { name: 'Connect Google/Outlook via Cal.com' }).click();
    await expect(page.getByRole('button', { name: 'Connected to Google Calendar ✓' })).toBeVisible();
  });

  test('Twilio: Toggle SMS Notifications in Operations', async ({ page }) => {
    await page.getByRole('button', { name: 'Operations' }).click();

    await expect(page.getByRole('heading', { name: 'Twilio SMS Notifications' })).toBeVisible();
    await page.getByLabel('Enable SMS Notifications via Twilio').check();

    await expect(page.getByText('✓ SMS alerts are now active globally.')).toBeVisible();
  });

  test('Mercado Pago: Configure LATAM region payment provider', async ({ page }) => {
    await page.getByRole('button', { name: 'Finance' }).click();
    await expect(page.getByRole('heading', { name: 'Finance & Payments' })).toBeVisible();

    await expect(page.getByRole('heading', { name: 'Store Region' })).toBeVisible();
    await page.locator('#region-selector').selectOption('LATAM');

    await expect(page.getByRole('heading', { name: 'Mercado Pago' })).toBeVisible();
    await expect(page.getByText('RECOMMENDED')).toBeVisible();

    await page.getByRole('button', { name: 'Connect Mercado Pago' }).click();
    await expect(page.getByRole('button', { name: 'Connected to Mercado Pago ✓' })).toBeVisible();
  });

  test('EasyPost: Print shipping label from order details', async ({ page }) => {
    // Click the mock order task on the dashboard
    await page.locator('div.card').filter({ hasText: 'New Order #1042' }).click();

    await expect(page.getByRole('heading', { name: 'Order #1042 Details' })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Fulfillment via EasyPost' })).toBeVisible();

    await page.getByRole('button', { name: 'Generate & Print Label' }).click();
    await expect(page.getByText('✓ Label generated via EasyPost and Tracking emailed to customer.')).toBeVisible();
  });

  test('Jitsi Meet: Auto-generated video link in meetings', async ({ page }) => {
    await page.getByRole('button', { name: 'Meetings' }).click();
    await expect(page.getByRole('heading', { name: 'AI Service Booking' })).toBeVisible();

    await expect(page.getByText('Online Meeting Link')).toBeVisible();
    await expect(page.getByText('meet.ohc.com/leo-guitar-session')).toBeVisible();
    await expect(page.getByText('Auto-generated via Jitsi Meet')).toBeVisible();
  });
});
