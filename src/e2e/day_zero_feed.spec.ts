import { test, expect } from '@playwright/test';

test.describe('Zero-Touch AI Onboarding & Proactive Agent Coordination', () => {
    test('Should generate Day Zero proactive action cards in the unified feed after onboarding', async ({ page }) => {
        // Setup mock environment overrides if needed

        // Start from onboarding
        await page.goto('/auth/onboarding');

        // Fill out business description
        await page.waitForSelector('textarea[name="description"]', { state: 'visible' });
        await page.fill('textarea[name="description"]', 'We are a small custom cake shop in Austin, Texas looking to sell cakes and cupcakes online.');
        await page.click('button:has-text("Generate Business")');

        // Verify we hit the generation phase and animation
        await expect(page.locator('text=Researching your market')).toBeVisible({ timeout: 15000 });

        // Let it finish and transition to sign up details
        await page.waitForSelector('input[name="admin_name"]', { state: 'visible', timeout: 30000 });
        await page.fill('input[name="admin_name"]', 'Maya Baker');
        await page.fill('input[name="admin_email"]', 'maya.baker.test@example.com');
        await page.fill('input[name="admin_password"]', 'Password123!');
        await page.click('button:has-text("Start My Business")');

        // Wait for redirection to dashboard
        await page.waitForURL('**/dashboard**', { timeout: 45000 });

        // Navigate to the dashboard index where the unified feed is
        // The dashboard should have proactive feed cards generated by our workers

        // Wait for feed to load
        await page.waitForSelector('[data-testid="agent-feed-item"]', { state: 'visible', timeout: 15000 });

        // Assert that the feed contains the drafted action cards
        await expect(page.locator('text=The Scout researched your market')).toBeVisible();
        await expect(page.locator('text=The Promoter drafted a 3-post \\"We are Open!\\"')).toBeVisible();
        await expect(page.locator('text=The Manager has drafted suggested operating hours')).toBeVisible();

        // Optionally interact with one to approve it to ensure full lifecycle
        const approveOpsBtn = page.locator('text=The Manager has drafted suggested operating hours').locator('..').locator('button:has-text("Approve")');
        if (await approveOpsBtn.count() > 0) {
            await approveOpsBtn.first().click();
            await expect(page.locator('text=The Manager has drafted suggested operating hours')).toBeHidden({ timeout: 10000 });
        }
    });
});
