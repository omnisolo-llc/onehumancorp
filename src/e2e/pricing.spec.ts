import { test, expect } from './fixtures';

test.describe('Pricing UI / Billing Portal', () => {
  test('renders pricing tiers and handles checkout session upgrade', async ({ memberPage }) => {
    const page = memberPage;
    // Login flow is handled by fixtures (memberPage)

    // Navigate to pricing page
    await page.goto('/pricing.html');

    // Wait for the grid to appear
    await expect(page.locator('#pricing-grid')).toBeVisible();

    // Verify all 4 tiers render
    await expect(page.locator('#card-free')).toBeVisible();
    await expect(page.locator('#card-starter')).toBeVisible();
    await expect(page.locator('#card-pro')).toBeVisible();
    await expect(page.locator('#card-business')).toBeVisible();

    // Expect the current plan to be indicated (Free by default locally unless seeded differently)
    const currentBtn = page.locator('#card-free button');
    await expect(currentBtn).toHaveText('Current Plan');

    // The other cards should have Upgrade buttons
    await expect(page.locator('#card-starter button')).toHaveText('Upgrade to Starter via Stripe');
    await expect(page.locator('#card-pro button')).toHaveText('Upgrade to Pro via Stripe');
    await expect(page.locator('#card-business button')).toHaveText('Upgrade to Business via Stripe');

    // Wait for the page to navigate to stripe checkout (or local fallback url generated by the backend).
    // The backend provides a fallback URL like `https://checkout.stripe.com/pay/test_starter_...` when stripe_client is none

    const [request] = await Promise.all([
      page.waitForRequest(req => req.url().includes('/api/billing/create-checkout-session')),
      page.click('#card-starter button')
    ]);

    expect(request.method()).toBe('POST');
    const body = JSON.parse(request.postData() || '{}');
    expect(body.tier).toBe('starter');
    expect(body.is_subscription).toBe(true);
  });

  test('cancel subscription handles request correctly', async ({ memberPage }) => {
    const page = memberPage;
    // Navigate to pricing page
    await page.goto('/pricing.html');

    // Wait for the grid to appear
    await expect(page.locator('#pricing-grid')).toBeVisible();

    // We cannot reliably trigger cancel button visibility from UI tests since my-plan is seeded as Free
    // However we can directly verify the cancel link's existence since the DOM element exists (hidden)
    const cancelLink = page.locator('#cancel-subscription-link');
    await expect(cancelLink).toHaveText('Cancel current subscription');

    // Call the cancel endpoint directly to ensure it works hermetically without UI manipulation issues
    const req = await page.request.post('/api/billing/cancel-subscription', { headers: { 'x-ohc-tenant-id': 'e2e-tenant' }});
    expect(req.status()).toBe(200);
  });

  test('should verify Back button functions', async ({ memberPage }) => {
    const page = memberPage;
    await page.goto('/pricing.html');
    const backButton = page.locator('a.back-link');
    await expect(backButton).toBeVisible();
    await backButton.click();
    await expect(page).toHaveURL(/.*dashboard\.html/);
  });

  test('should verify upgrade to Pro button routes to checkout', async ({ memberPage }) => {
    const page = memberPage;
    await page.goto('/pricing.html');
    const upgradeButton = page.locator('button', { hasText: 'Upgrade to Pro via Stripe' });
    await expect(upgradeButton).toBeVisible();

    const [request] = await Promise.all([
      page.waitForRequest(req => req.url().includes('/api/billing/create-checkout-session')),
      page.click('#card-pro button')
    ]);

    expect(request.method()).toBe('POST');
    const body = JSON.parse(request.postData() || '{}');
    expect(body.tier).toBe('pro');
    expect(body.is_subscription).toBe(true);
  });

  test('should verify upgrade to Business button routes to checkout', async ({ memberPage }) => {
    const page = memberPage;
    await page.goto('/pricing.html');
    const upgradeButton = page.locator('button', { hasText: 'Upgrade to Business via Stripe' });
    await expect(upgradeButton).toBeVisible();

    const [request] = await Promise.all([
      page.waitForRequest(req => req.url().includes('/api/billing/create-checkout-session')),
      page.click('#card-business button')
    ]);

    expect(request.method()).toBe('POST');
    const body = JSON.parse(request.postData() || '{}');
    expect(body.tier).toBe('business');
    expect(body.is_subscription).toBe(true);
  });

});
