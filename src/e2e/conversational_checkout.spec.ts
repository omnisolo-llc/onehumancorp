import { test, expect } from '@playwright/test';

test.describe('Conversational Checkout & Instant Deposit Flow (Persona: Maya)', () => {
    test.beforeEach(async ({ page }) => {
        // Authenticate as Maya via standard UI
        await page.goto('/login');
        await page.fill('input[name="email"]', 'maya@bakery.com');
        await page.fill('input[name="password"]', 'password123');
        await page.click('button[type="submit"]');
        await expect(page).toHaveURL(/.*dashboard/);
    });

    test('Maya can generate an instant deposit link in DM Inbox', async ({ page }) => {
        // 1. Navigate to Unified Inbox
        await page.click('text=Inbox');
        await expect(page).toHaveURL(/.*inbox/);

        // 2. Select a customer DM thread
        await page.click('text=Carlos Handyman'); // Example customer
        await expect(page.locator('.chat-thread')).toBeVisible();

        // 3. AI Agent suggests "Generate Deposit Link"
        const aiSuggestion = page.locator('button:has-text("Generate Deposit Link")');
        await expect(aiSuggestion).toBeVisible();
        await aiSuggestion.click();

        // 4. Maya confirms the generated conversational checkout modal
        const depositModal = page.locator('.checkout-generator-modal');
        await expect(depositModal).toBeVisible();

        await page.fill('input[name="deposit_amount"]', '50.00');
        await page.click('button:has-text("Send to Customer")');

        // 5. Verify the link is generated and sent in chat
        await expect(page.locator('.chat-thread')).toContainText('https://checkout.ohc.network/pay/');

        // 6. Navigate to Ledger/Finances to check pending deposits (optional proxy verification)
        await page.click('text=Finance');
        await expect(page.locator('.pending-deposits-list')).toContainText('$50.00');
    });

    test('Customer can access the generated conversational checkout link and see payment UI', async ({ page }) => {
        // 1. As a customer, navigate directly to a mocked checkout link generated by the system
        // We simulate a generated session id here
        const session_id = 'test-session-1234';
        await page.goto(`/pay/${session_id}`);

        // 2. Verify mobile-first checkout UI renders
        const checkoutContainer = page.locator('.checkout-container');
        await expect(checkoutContainer).toBeVisible();

        // 3. Verify it shows the correct amount
        await expect(page.locator('.checkout-amount')).toContainText('$50.00');

        // 4. Verify payment options exist (e.g., Apple Pay, Pix, Card)
        await expect(page.locator('button:has-text("Pay with Card")')).toBeVisible();
    });
});
