import { test, expect } from '@playwright/test';

test.describe('AIaaS Workflow e2e', () => {
  test('User can trigger an AIaaS workflow and approve it in the inbox', async ({ page }) => {
    // Navigate to dashboard
    await page.goto('/dashboard');

    // Simulate logging in by setting local storage token
    await page.evaluate(() => {
      localStorage.setItem('tenant', 'test-tenant');
      localStorage.setItem('token', 'test-token');
    });

    // We trigger the backend API to simulate a background job
    // Usually this would be done by the agent spontaneously or via a scheduled job
    const triggerResponse = await page.request.post('/api/agents/aiaas/trigger', {
      headers: {
        'x-tenant-id': 'test-tenant',
      },
      data: {
        workflow_type: 'custom_blog_post',
        persona_name: 'Blog Writer',
        system_prompt: 'You write good blogs.',
        capabilities: ['write_blog'],
        payload: {
          context: 'Summer Sale 2024'
        }
      }
    });

    // The backend should succeed
    expect(triggerResponse.ok()).toBeTruthy();
    const data = await triggerResponse.json();
    expect(data.success).toBeTruthy();
    expect(data.workflow_id).toBeDefined();

    // Now navigate to the Team page
    await page.goto('/team');

    // Select Business Advisory (the department we route AIaaS workflows to)
    const advisorCard = page.locator('text=The Advisor');
    await advisorCard.click();

    // Wait for the Approval Inbox to appear
    await expect(page.locator('text=Approval Inbox')).toBeVisible();

    // Check if the AIaaS workflow item is visible
    await expect(page.locator(`text=${data.workflow_id}`)).toBeVisible();
    await expect(page.locator('text=Blog Writer')).toBeVisible();
    await expect(page.locator('text=AI Draft generated by Blog Writer')).toBeVisible();

    // Approve it
    const approveButton = page.locator('button:has-text("Approve")').first();
    await approveButton.click();

    // The item should eventually disappear as it gets approved and re-fetched
    // For now, just ensure we could click it and no errors were thrown
  });
});
