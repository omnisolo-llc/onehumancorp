'use client';
import { useState } from 'react';
import Link from 'next/link';
import { useRouter } from 'next/navigation';

export default function NewServicePage() {
  const router = useRouter();
  const [title, setTitle] = useState('');
  const [description, setDescription] = useState('');
  const [isRecurring, setIsRecurring] = useState(false);
  const [frequency, setFrequency] = useState('monthly');
  const [price, setPrice] = useState('');
  const [saved, setSaved] = useState(false);
  const [generateIntake, setGenerateIntake] = useState(false);
  const [templateId, setTemplateId] = useState('');

  const handleSave = async () => {
    if (!title) return;
    try {
      const tenant = typeof localStorage !== 'undefined' ? localStorage.getItem('tenant') || 'my-store' : 'my-store';
      const userId = typeof localStorage !== 'undefined' ? localStorage.getItem('user_id') || 'anon' : 'anon';

      // Save service logic
      await fetch('/api/onboarding/state', {
         method: 'POST',
         headers: { 'Content-Type': 'application/json', 'X-Tenant-ID': tenant, 'X-User-ID': userId },
         body: JSON.stringify({ services: [{ title, description, price }] })
      });

      if (generateIntake) {
         const res = await fetch('/api/v1/questionnaires', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json', 'X-Tenant-ID': tenant },
            body: JSON.stringify({ title: `${title} Intake Form`, service_id: 'mock-service-id' })
         });
         if (res.ok) {
            const data = await res.json();
            setTemplateId(data.id);
            setSaved(true);
            return;
         }
      }

      setSaved(true);
      setTimeout(() => router.push('/dashboard'), 1500);
    } catch (e) { console.error(e); }
  };

  const autoGenerateDescription = () => {
    setDescription('A weekly music tutoring session focused on improving technique, music theory, and performance skills. Perfect for students of all levels.');
  };

  if (saved) {
    return (
      <div className="p-4 max-w-md mx-auto mt-20 text-center">
        <h2 className="text-2xl font-bold text-green-600 mb-2">Service Saved!</h2>
        {templateId ? (
           <div className="mt-6 bg-blue-50 p-4 rounded-xl border border-blue-100">
             <h3 className="font-semibold text-blue-900 mb-2">Intake Questionnaire Generated</h3>
             <p className="text-sm text-gray-700 mb-4">You can now share this form with clients to collect information.</p>
             <Link href={`/intake/${templateId}`} className="text-blue-600 hover:underline bg-white px-4 py-2 rounded-lg shadow-sm font-medium">
                View Generated Form
             </Link>
             <div className="mt-4">
                <Link href="/dashboard/intakes" className="text-sm text-gray-500 hover:underline">Go to Dashboard</Link>
             </div>
           </div>
        ) : (
           <p>Redirecting to dashboard...</p>
        )}
      </div>
    );
  }

  return (
    <div className="p-4 max-w-md mx-auto">
      <div className="flex items-center mb-6">
        <Link href="/dashboard" className="mr-4 text-blue-500 hover:text-blue-700">
          &lt; Back
        </Link>
        <h1 className="text-2xl font-bold">Add Service</h1>
      </div>

      <div className="space-y-4">
        <div>
          <label className="block text-sm font-medium text-gray-700 mb-1">Service Title</label>
          <input
            type="text"
            value={title}
            onChange={e => setTitle(e.target.value)}
            className="w-full border rounded-lg p-3 text-black focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none"
            placeholder="e.g. Custom Flooring Install"
            required
          />
        </div>

        <div>
          <div className="flex justify-between items-center mb-1">
            <label className="block text-sm font-medium text-gray-700">Description</label>
            <button
              onClick={autoGenerateDescription}
              className="text-xs text-purple-600 hover:text-purple-800 flex items-center bg-purple-50 px-2 py-1 rounded"
            >
              ✨ Auto-draft
            </button>
          </div>
          <textarea
            value={description}
            onChange={e => setDescription(e.target.value)}
            className="w-full border rounded-lg p-3 text-black h-24 focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none"
            placeholder="Describe the service..."
          />
        </div>

        <div>
          <label className="block text-sm font-medium text-gray-700 mb-1">Price</label>
          <div className="relative">
            <span className="absolute left-3 top-3 text-gray-500">$</span>
            <input
              type="number"
              value={price}
              onChange={e => setPrice(e.target.value)}
              className="w-full border rounded-lg p-3 pl-8 text-black focus:ring-2 focus:ring-blue-500 focus:border-blue-500 outline-none"
              placeholder="0.00"
            />
          </div>
        </div>

        <div className="border-t border-gray-100 pt-4 mt-6">
           <div className="bg-gradient-to-r from-blue-50 to-purple-50 p-4 rounded-xl border border-blue-100/50 relative overflow-hidden">
              <div className="flex items-start">
                 <div className="pt-0.5">
                    <input
                       type="checkbox"
                       id="generate-intake"
                       checked={generateIntake}
                       onChange={e => setGenerateIntake(e.target.checked)}
                       className="w-5 h-5 text-blue-600 rounded border-gray-300 focus:ring-blue-500"
                    />
                 </div>
                 <div className="ml-3">
                    <label htmlFor="generate-intake" className="font-medium text-gray-900 cursor-pointer">
                       Auto-generate Intake Questionnaire
                    </label>
                    <p className="text-sm text-gray-600 mt-1">
                       Operations Agent will create an intake form to collect necessary details before booking (e.g., room dimensions, materials).
                    </p>
                 </div>
              </div>
           </div>
        </div>

        <div className="pt-6 border-t mt-4">
          <div className="flex items-center justify-between mb-4">
            <div>
              <h3 className="font-medium">Recurring Payment</h3>
              <p className="text-sm text-gray-500">Automatically bill customers for this service.</p>
            </div>
            <label className="relative inline-flex items-center cursor-pointer">
              <input
                type="checkbox"
                checked={isRecurring}
                onChange={() => setIsRecurring(!isRecurring)}
                className="sr-only peer"
              />
              <div className="w-11 h-6 bg-gray-200 peer-focus:outline-none peer-focus:ring-4 peer-focus:ring-blue-300 rounded-full peer peer-checked:after:translate-x-full peer-checked:after:border-white after:content-[''] after:absolute after:top-[2px] after:left-[2px] after:bg-white after:border-gray-300 after:border after:rounded-full after:h-5 after:w-5 after:transition-all peer-checked:bg-blue-600"></div>
            </label>
          </div>

          {isRecurring && (
            <div className="bg-gray-50 p-3 rounded-lg border">
              <label className="block text-sm font-medium text-gray-700 mb-1">Billing Frequency</label>
              <select
                value={frequency}
                onChange={e => setFrequency(e.target.value)}
                className="w-full border rounded-lg p-3 text-black bg-white"
              >
                <option value="weekly">Weekly</option>
                <option value="biweekly">Every 2 weeks</option>
                <option value="monthly">Monthly</option>
                <option value="yearly">Yearly</option>
              </select>
            </div>
          )}
        </div>

        <div className="pt-6">
          <button
            onClick={handleSave}
            className="w-full bg-black text-white font-medium py-4 rounded-xl shadow-lg hover:bg-gray-800 transition"
          >
            Save Service
          </button>
        </div>
      </div>
    </div>
  );
}
