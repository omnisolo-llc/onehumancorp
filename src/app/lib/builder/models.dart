/// Represents a discrete, functional chunk of content within a storefront layout.
///
/// The `Block` is the fundamental unit of composition in the OHC Website Builder architecture.
/// Instead of allowing users to place arbitrary HTML/CSS elements, the system enforces
/// design constraints by abstracting features into these predefined blocks (e.g., Hero, Product Grid).
///
/// This JSON-serializable model allows the layout to be easily transmitted between
/// the Dart/Flutter client, the Rust backend API, and stored efficiently in PostgreSQL.
class Block {
  /// A globally unique identifier for this specific block instance.
  /// Typically a UUID generated by the backend upon creation.
  final String id;

  /// A string literal defining the functional component this block represents.
  /// The `StorefrontEngine` uses this identifier to select the appropriate rendering widget.
  ///
  /// Expected values include: 'HeroBlock', 'ProductGridBlock', 'ContactFormBlock', etc.
  final String blockType;

  /// A dynamic map containing the configuration and content specific to this block type.
  ///
  /// For example, a `HeroBlock` might contain `{'headline': 'Welcome', 'subtitle': 'Store'}`.
  /// This schema-less approach allows ultimate flexibility without requiring database migrations
  /// every time a new block type or field is introduced.
  final Map<String, dynamic> content;

  /// An integer denoting the vertical rendering order of this block relative to other blocks on the same page.
  /// Lower values are rendered higher up on the screen.
  final int sortOrder;

  /// Constructs a new `Block` instance.
  Block({
    required this.id,
    required this.blockType,
    required this.content,
    required this.sortOrder
  });

  /// Factory method to construct a `Block` from a JSON map.
  ///
  /// This is used heavily when deserializing responses from the backend API.
  factory Block.fromJson(Map<String, dynamic> json) {
    return Block(
      id: json['id'],
      blockType: json['block_type'],
      content: json['content'] as Map<String, dynamic>,
      sortOrder: json['sort_order'],
    );
  }

  /// Converts the `Block` instance back into a JSON map for serialization.
  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'block_type': blockType,
      'content': content,
      'sort_order': sortOrder,
    };
  }
}
