import 'package:flutter/material.dart';
import 'models.dart';

/// The StorefrontEngine is responsible for interpreting a sequence of `Block` models
/// and rendering them as a coherent, mobile-first storefront interface.
///
/// This component is the primary rendering layer for the Website Builder feature.
/// It takes a declarative JSON-based configuration (represented by the `Block` objects)
/// and dynamically constructs the corresponding Flutter widget tree. This allows
/// non-technical users to build and modify their storefronts simply by changing
/// the underlying data structure, which is then immediately reflected in this UI.
///
/// Key design principles behind the StorefrontEngine:
/// 1. **Block-Based Architecture**: Rather than a free-form canvas, the storefront
///    is composed of predefined, functionally complete blocks (e.g., HeroBlock,
///    ProductGridBlock). This eliminates choice paralysis and ensures a consistently
///    high-quality, responsive layout out of the box.
/// 2. **Mobile-First Rendering**: Every block is designed to look perfect on a 375px
///    screen, adhering to the "grandmother test". The layout adapts gracefully to
///    larger screens but prioritizes the mobile experience.
/// 3. **Declarative State Interpretation**: The engine holds no internal state regarding
///    the storefront content; it is a pure function of its `blocks` input.
/// 4. **Extensibility**: The `switch` statement inside `_buildBlock` acts as a registry.
///    New block types can be seamlessly added by defining a new case and a corresponding
///    widget renderer.
///
/// The `StorefrontEngine` is utilized both in the "Preview" mode of the `StorefrontEditor`
/// and in the final published, read-only view of the storefront.
class StorefrontEngine extends StatelessWidget {
  /// The ordered sequence of content blocks that constitute the storefront page.
  /// The rendering order strictly follows the order of this list.
  final List<Block> blocks;

  /// Constructs a `StorefrontEngine`.
  ///
  /// The [blocks] parameter must not be null and should be pre-sorted according
  /// to the intended visual flow (e.g., via the `sortOrder` property of each block).
  const StorefrontEngine({Key? key, required this.blocks}) : super(key: key);

  @override
  Widget build(BuildContext context) {
    return ListView.builder(
      // The ListView handles scrolling automatically and builds children lazily
      // for optimal performance, even with a large number of blocks.
      itemCount: blocks.length,
      itemBuilder: (context, index) {
        final block = blocks[index];
        return _buildBlock(block);
      },
    );
  }

  /// Maps a declarative `Block` model to its corresponding Flutter Widget.
  ///
  /// This method acts as the factory for visual components. It inspects the
  /// `blockType` string and delegates the rendering to the appropriate sub-widget
  /// or inline widget tree.
  ///
  /// Supported Block Types:
  /// - `HeroBlock`: A prominent top-of-page banner with a headline and optional subtitle.
  /// - `ProductGridBlock`: A responsive grid displaying products or services.
  /// - `ContactFormBlock`: A form allowing customers to send messages to the business.
  /// - `TestimonialBlock`: A list or carousel of customer reviews.
  /// - `ServiceBookingBlock`: A list of services with actionable "Book" buttons.
  /// - `BookingCalendarBlock`: A placeholder for an interactive calendar widget.
  ///
  /// If a `blockType` is unrecognized, a `SizedBox.shrink()` is returned to gracefully
  /// ignore the unknown content without breaking the layout.
  Widget _buildBlock(Block block) {
    switch (block.blockType) {
      case 'HeroBlock':
        return Container(
          padding: EdgeInsets.all(20),
          decoration: BoxDecoration(
            color: Colors.white.withOpacity(0.8),
          ),
          child: Column(
            children: [
              Text(
                block.content['headline'] ?? '',
                style: TextStyle(fontFamily: 'Outfit', fontSize: 24, fontWeight: FontWeight.bold),
              ),
              if (block.content['subtitle'] != null)
                Text(
                  block.content['subtitle'],
                  style: TextStyle(fontFamily: 'Inter', fontSize: 16),
                ),
            ],
          ),
        );
      case 'ProductGridBlock':
        final items = block.content['items'] as List<dynamic>? ?? [];
        return GridView.builder(
          shrinkWrap: true,
          physics: NeverScrollableScrollPhysics(),
          gridDelegate: SliverGridDelegateWithFixedCrossAxisCount(
            crossAxisCount: 2,
            childAspectRatio: 0.8,
          ),
          itemCount: items.length,
          itemBuilder: (context, index) {
            final item = items[index];
            return Card(
              child: Center(child: Text(item.toString())),
            );
          },
        );
      case 'ContactFormBlock':
        return Container(
          padding: EdgeInsets.all(20),
          child: Column(
            children: [
              Text(block.content['title'] ?? 'Contact Us', style: TextStyle(fontSize: 20)),
              TextField(decoration: InputDecoration(labelText: 'Email')),
              TextField(decoration: InputDecoration(labelText: 'Message')),
              ElevatedButton(onPressed: () {}, child: Text('Send')),
            ],
          )
        );
      case 'TestimonialBlock':
        final testimonials = block.content['testimonials'] as List<dynamic>? ?? [];
        return ListView.builder(
          shrinkWrap: true,
          physics: NeverScrollableScrollPhysics(),
          itemCount: testimonials.length,
          itemBuilder: (context, index) {
            return ListTile(
              leading: Icon(Icons.person),
              title: Text(testimonials[index].toString()),
            );
          }
        );
      case 'ServiceBookingBlock':
        final services = block.content['services'] as List<dynamic>? ?? [];
        return Column(
          children: services.map((s) => ListTile(
            title: Text(s.toString()),
            trailing: ElevatedButton(onPressed: () {}, child: Text('Book')),
          )).toList(),
        );
      case 'BookingCalendarBlock':
        return Container(
          padding: EdgeInsets.all(20),
          child: Text('Booking Calendar Widget Placeholder'),
        );
      default:
        // Graceful fallback for unrecognized block types to prevent UI crashes.
        return SizedBox.shrink();
    }
  }
}

