import { test, expect } from '@playwright/test';

test.describe('Onboarding E2E flow', () => {
  test('User completes 8-step business setup wizard', async ({ page }) => {
    // 1. Landing Screen -> Login
    await page.goto('http://127.0.0.1:8081/#/landing');

    // In our app, landing page provides a "Start Business Setup" directly, or "Or continue to Cloud Dashboard" (login).
    // Let's use the explicit button to start the business setup.
    await page.waitForTimeout(5000);
    await page.mouse.wheel(0, 500);
    await page.waitForTimeout(1000);
    await page.getByText('Start Business Setup').click();

    // Since the user is not authenticated, they get redirected to /login first
    // Wait for the login screen
    await expect(page.getByText('Sign in to orchestrate your swarm')).toBeVisible({ timeout: 20000 });
    await page.getByLabel('Email or Username').fill('maya_baker');
    await page.getByLabel('Password').fill('test_password123');
    await page.getByText('Sign In').click();

    // Wait for auth to complete and redirection back to /business_setup
    // In the test environment, we might get directed to the first step of the setup
    await expect(page.getByText('Welcome! Your AI team, ready in minutes.')).toBeVisible({ timeout: 20000 });

    // Step 0 -> Step 1 (Business Profile)
    await page.getByText('Next').click();

    // Step 1: Business Profile
    await page.getByLabel('Company Name').fill('Maya Custom Cakes');
    await page.getByLabel('Industry').fill('Baking');
    await page.getByText('Next').click();

    // Step 2: Goal selection & Payment Preference
    await expect(page.getByText('Select Goals')).toBeVisible();
    await page.getByText('Support').click();
    await page.getByText('Marketing').click();
    // Payment preference defaults to Stripe
    await page.getByText('Next').click();

    // Step 3: Template Selection
    await expect(page.getByText('Template Selection')).toBeVisible();
    await page.getByText('Modern Minimal').click();
    await page.getByText('Next').click();

    // Step 4: First Product / Service
    await expect(page.getByText('First Product / Service')).toBeVisible();
    await page.getByLabel('Product Name').fill('Vegan Chocolate Cake');
    // Description is auto-generated by our simulated AI
    await page.waitForTimeout(500);
    await expect(page.getByLabel('AI Description')).toHaveValue('A fantastic Vegan Chocolate Cake that will delight you!');
    await page.getByLabel('Price').fill('45.00');
    await page.getByText('Next').click();

    // Step 5: Domain & Go-Live
    await expect(page.getByText('Domain & Go-Live')).toBeVisible();
    await page.getByLabel('Subdomain (e.g., mybusiness)').fill('mayacakes');
    await page.getByText('Publish').click();

    // Step 6: Deployment Preference
    await expect(page.getByText('Deployment Preference')).toBeVisible();
    // Use default cloud deployment
    await page.getByText('Next').click();

    // Step 7: Administrator Account
    await expect(page.getByLabel('Admin Name')).toBeVisible();
    await page.getByLabel('Admin Name').fill('Maya');
    await page.getByLabel('Admin Email').fill('maya@example.com');
    await page.getByLabel('Admin Password').fill('securepassword123');
    await page.getByText('Next').click();

    // Step 8: Welcome Checklist
    await expect(page.getByText('Welcome Checklist')).toBeVisible();
    await expect(page.getByText('🎉 Confetti! 🎉')).toBeVisible();

    // Finish Setup
    await page.getByText('Launch My AI Team →').click();

    // Expect to land on the dashboard
    await expect(page).toHaveURL(/.*\/dashboard/);
    await expect(page.getByText('Dashboard')).toBeVisible();
  });
});
