import { test, expect } from '@playwright/test';

test.describe('Autonomous Reputation & Referral Engine CUJ', () => {
  test('Non-technical owner can verify reputation and review engine workflow', async ({ page }) => {
    // 1. Owner logs into OHC dashboard
    await page.goto('/dashboard');

    // 2. Navigate to Reputation page
    await page.goto('/reputation');

    // We expect the app to load without error
    const title = await page.title();
    expect(title).toBeDefined();

    // Verify UI components are visible
    await expect(page.getByText('Your Reputation Pulse')).toBeVisible({ timeout: 10000 });
    await expect(page.getByText('Unified Review Inbox')).toBeVisible();

    // Wait for reviews to load or empty state
    const loadingText = page.locator('text=Loading reviews...');
    await loadingText.waitFor({ state: 'hidden', timeout: 15000 });

    // Assuming the database is properly seeded or starting empty, we verify the empty state fallback correctly if there's no review.
    // If there is a review seeded, verify it.
    const emptyState = page.getByText('No reviews yet.');
    const reviewCards = page.locator('text=Customer');

    // Either it shows the empty state or review cards
    const isEmpty = await emptyState.isVisible();
    if (isEmpty) {
        // App safely handled empty state
        expect(true).toBeTruthy();
    } else {
        // Look for the "Approve & Post" button generated by The Publicist draft
        const approveButton = page.getByRole('button', { name: 'Approve & Post' }).first();

        if (await approveButton.isVisible()) {
          await approveButton.click();

          // Wait for optimistic update or state change to show it was approved
          await expect(page.getByText('Replied').first()).toBeVisible({ timeout: 5000 });
        }
    }
  });
});
