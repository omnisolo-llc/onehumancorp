func TestNetworkProxy_Allowed(t *testing.T) {
	telemetry := &MockTelemetryEmitter{}
	proxy := NewNetworkProxy([]string{"example.com"}, telemetry)

	req := httptest.NewRequest(http.MethodGet, "http://example.com/", nil)
	req.Host = "example.com"
	rr := httptest.NewRecorder()

	// Replace the actual external call with a simple response for testing.
	// In a real scenario, we might use httputil.ReverseProxy and mock the backend.
	// For this test, we just check if it gets blocked or not.

	proxyHandler := http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if !proxy.isAllowed(r.Host) {
			proxy.Telemetry.EmitViolation(r.Host)
			http.Error(w, "Forbidden by Sandbox Policy", http.StatusForbidden)
			return
		}
		w.WriteHeader(http.StatusOK)
	})

	proxyHandler.ServeHTTP(rr, req)

	if status := rr.Code; status != http.StatusOK {
		t.Errorf("handler returned wrong status code: got %v want %v",
			status, http.StatusOK)
	}

	telemetry.mu.Lock()
	defer telemetry.mu.Unlock()
	if len(telemetry.Violations) != 0 {
		t.Errorf("Expected 0 violations, got %d", len(telemetry.Violations))
	}
}

func TestNetworkProxy_Denied(t *testing.T) {
	telemetry := &MockTelemetryEmitter{}
	proxy := NewNetworkProxy([]string{"example.com"}, telemetry)

	req := httptest.NewRequest(http.MethodGet, "http://evil.com/", nil)
	req.Host = "evil.com"
	rr := httptest.NewRecorder()

	proxy.ServeHTTP(rr, req)

	if status := rr.Code; status != http.StatusForbidden {
		t.Errorf("handler returned wrong status code: got %v want %v",
			status, http.StatusForbidden)
	}

	telemetry.mu.Lock()
	defer telemetry.mu.Unlock()
	if len(telemetry.Violations) != 1 {
		t.Fatalf("Expected 1 violation, got %d", len(telemetry.Violations))
	}
	if telemetry.Violations[0] != "evil.com" {
		t.Errorf("Expected violation for evil.com, got %s", telemetry.Violations[0])
	}
}
