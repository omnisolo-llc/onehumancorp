package harness

import (
	"context"
	"fmt"
	"os/exec"
)

type BwrapExecutor struct {
	AllowedDomains []string
}

func NewBwrapExecutor(allowedDomains []string) *BwrapExecutor {
	return &BwrapExecutor{
		AllowedDomains: allowedDomains,
	}
}

func (b *BwrapExecutor) Execute(ctx context.Context, cmdString string, proxyURL string) (string, error) {
	args := []string{
		"--ro-bind", "/", "/",
		"--dev", "/dev",
		"--proc", "/proc",
		"--tmpfs", "/tmp",
		"--unshare-all",
		"--share-net",
		"--setenv", "HTTP_PROXY", proxyURL,
		"--setenv", "HTTPS_PROXY", proxyURL,
		"--", "sh", "-c", cmdString,
	}

	cmd := exec.CommandContext(ctx, "bwrap", args...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return string(out), fmt.Errorf("bwrap execution failed: %v, output: %s", err, string(out))
	}
	return string(out), nil
}
