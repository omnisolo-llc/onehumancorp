import 'dart:convert';
import 'package:http/http.dart' as http;

class ApiService {
  Future<String> autoGenerateDescription(String productName) async {
    final url = Uri.parse('https://api.onehumancorp.com/api/onboarding/generate-description');
    try {
      final response = await http.post(
        url,
        headers: {'Content-Type': 'application/json'},
        body: json.encode({'productName': productName}),
      );
      if (response.statusCode == 200) {
        final body = json.decode(response.body);
        return body['description'] ?? 'Generated description for $productName';
      } else {
        print('Failed to generate description: ${response.statusCode}');
        return 'Generated description for $productName (fallback)';
      }
    } catch (e) {
      print('Error generating description: $e');
      return 'Generated description for $productName (error)';
    }
  }

  Future<void> submitBusinessData(Map<String, dynamic> data) async {
    final url = Uri.parse('/api/onboarding/start');
    try {
      final response = await http.post(
        url,
        headers: {'Content-Type': 'application/json'},
        body: json.encode({
          'name': data['companyName'] ?? '',
          'category': data['industry'] ?? '',
          'description': data['productDescription'] ?? '',
        }),
      );
      if (response.statusCode == 202) {
        print('Business data submitted successfully: ${response.body}');
      } else {
        print('Failed to submit business data: ${response.statusCode}');
      }
    } catch (e) {
      print('Error submitting business data: $e');
    }
  }

  Future<void> saveState(Map<String, dynamic> state, String tenantId) async {
    final url = Uri.parse('/api/onboarding/state');
    try {
      final response = await http.post(
        url,
        headers: {
          'Content-Type': 'application/json',
          'X-Tenant-Id': tenantId,
        },
        body: json.encode({'state': json.encode(state)}),
      );
      if (response.statusCode != 204) {
        print('Failed to save state: ${response.statusCode}');
      }
    } catch (e) {
      print('Error saving state: $e');
    }
  }

  Future<Map<String, dynamic>?> getState(String tenantId) async {
    final url = Uri.parse('/api/onboarding/state');
    try {
      final response = await http.get(
        url,
        headers: {'X-Tenant-Id': tenantId},
      );
      if (response.statusCode == 200) {
        final body = json.decode(response.body);
        if (body['state'] != null && body['state'].isNotEmpty) {
           return json.decode(body['state']);
        }
      }
    } catch (e) {
      print('Error getting state: $e');
    }
    return null;
  }
}
