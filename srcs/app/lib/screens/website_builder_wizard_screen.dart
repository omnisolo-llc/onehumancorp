class WebsiteBuilderState {
  final int step;
  final String template;
  final String brandColor;
  final String productName;
  final String productPrice;
  final String productDescription;
  final String domainOption;
  final String domainName;
  final bool isAdvancedMode;
  final bool isLoading;
  final String? errorMessage;
  final String? publishedUrl;

  const WebsiteBuilderState({
    this.step = 0,
    this.template = '',
    this.brandColor = '',
    this.productName = '',
    this.productPrice = '',
    this.productDescription = '',
    this.domainOption = 'Free Subdomain',
    this.domainName = '',
    this.isAdvancedMode = false,
    this.isLoading = false,
    this.errorMessage,
    this.publishedUrl,
  });

  WebsiteBuilderState copyWith({
    int? step,
    String? template,
    String? brandColor,
    String? productName,
    String? productPrice,
    String? productDescription,
    String? domainOption,
    String? domainName,
    bool? isAdvancedMode,
    bool? isLoading,
    String? errorMessage,
    String? publishedUrl,
  }) {
    return WebsiteBuilderState(
      step: step ?? this.step,
      template: template ?? this.template,
      brandColor: brandColor ?? this.brandColor,
      productName: productName ?? this.productName,
      productPrice: productPrice ?? this.productPrice,
      productDescription: productDescription ?? this.productDescription,
      domainOption: domainOption ?? this.domainOption,
      domainName: domainName ?? this.domainName,
      isAdvancedMode: isAdvancedMode ?? this.isAdvancedMode,
      isLoading: isLoading ?? this.isLoading,
      errorMessage: errorMessage ?? this.errorMessage,
      publishedUrl: publishedUrl ?? this.publishedUrl,
    );
  }
}

class WebsiteBuilderNotifier extends Notifier<WebsiteBuilderState> {
  @override
  WebsiteBuilderState build() => const WebsiteBuilderState();

  void nextStep() {
    if (state.step < 4) {
      state = state.copyWith(step: state.step + 1);
    }
  }

  void prevStep() {
    if (state.step > 0) {
      state = state.copyWith(step: state.step - 1);
    }
  }

  void updateTemplate(String val) => state = state.copyWith(template: val);
  void updateBrandColor(String val) => state = state.copyWith(brandColor: val);
  void updateProductName(String val) => state = state.copyWith(productName: val);
  void updateProductPrice(String val) => state = state.copyWith(productPrice: val);
  void updateProductDescription(String val) => state = state.copyWith(productDescription: val);
  void updateDomainOption(String val) => state = state.copyWith(domainOption: val);
  void updateDomainName(String val) => state = state.copyWith(domainName: val);
  void toggleAdvancedMode() => state = state.copyWith(isAdvancedMode: !state.isAdvancedMode);

  void autoGenerateDescription() {
    // Mock AI generation
    state = state.copyWith(productDescription: "A beautiful, hand-crafted ${state.productName} perfect for any occasion.");
  }

  Future<void> launch(BuildContext context, WidgetRef ref) async {
    final user = ref.read(authStateProvider).valueOrNull;
    final baseUrl = ref.read(backendUrlProvider);

    state = state.copyWith(isLoading: true, errorMessage: null);

    if (user != null && baseUrl.isNotEmpty) {
      final body = {
        'template': state.template,
        'brand_color': state.brandColor,
        'product_name': state.productName,
        'product_price': state.productPrice,
        'product_description': state.productDescription,
        'domain_option': state.domainOption,
        'domain_name': state.domainName,
      };

      try {
        final res = await http.post(
          Uri.parse('$baseUrl/api/wizard/website'),
          headers: {
            'Authorization': 'Bearer ${user.token}',
            'Content-Type': 'application/json',
          },
          body: jsonEncode(body),
        );

        if (res.statusCode != 200) {
          state = state.copyWith(isLoading: false, errorMessage: 'Website publish failed: ${res.statusCode}');
          return;
        }
      } catch (e) {
        state = state.copyWith(isLoading: false, errorMessage: 'Network error: $e');
        return;
      }
    }

    state = state.copyWith(isLoading: false, publishedUrl: 'https://mybusiness.ohc.app');
  }
}

final websiteBuilderProvider = NotifierProvider<WebsiteBuilderNotifier, WebsiteBuilderState>(() {
  return WebsiteBuilderNotifier();
});

